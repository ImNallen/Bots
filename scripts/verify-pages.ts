import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { api } from "@bots/convex";
import { PAGE_LIMITS, pageView } from "@bots/protocol";
import { ConvexHttpClient } from "convex/browser";
import { importJWK, SignJWT } from "jose";
import { parsePrivateJwk, paths, readEnvFile } from "./lib.ts";

const env = readEnvFile(paths.rootEnv);
assert(env.CONVEX_URL?.startsWith("http://127.0.0.1:"), "Only a local backend is allowed");
assert.equal(readEnvFile(paths.convexEnv).CONVEX_SELF_HOSTED_URL, env.CONVEX_URL, "CLI fixtures and API checks must use the same local backend");
assert(env.JWT_PRIVATE_JWK && env.JWT_ISSUER);
const jwk = parsePrivateJwk(env.JWT_PRIVATE_JWK);
const key = await importJWK(jwk, "ES256");
const client = async (subject: string) => {
  const token = await new SignJWT({ email: `${subject}@example.test`, name: subject }).setProtectedHeader({ alg: "ES256", kid: jwk.kid }).setIssuer(env.JWT_ISSUER!).setAudience("bots").setSubject(subject).setIssuedAt().setExpirationTime("1h").sign(key);
  const service = new ConvexHttpClient(env.CONVEX_URL!);
  service.setAuth(token);
  return service;
};
const internal = (name: string, args: object): unknown => {
  const output = execFileSync("pnpm", ["exec", "convex", "run", name, JSON.stringify(args)], { cwd: "packages/convex", encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  return output.trim() === "" ? null : JSON.parse(output);
};
const service = await client("service:orchestrator");
const owner = await client(`dev:page-${randomUUID()}`);
const stranger = await client(`dev:stranger-${randomUUID()}`);
const anonymous = new ConvexHttpClient(env.CONVEX_URL!);
await owner.mutation(api.users.ensureCurrent, {});
await stranger.mutation(api.users.ensureCurrent, {});
const botId = await owner.mutation(api.bots.create, { name: "Page lifecycle proof" });
const threadId = await owner.mutation(api.threads.ensureForBot, { botId });
const runId = await owner.mutation(api.threads.send, { threadId, text: "Page fixture" });
const claim = await service.mutation(api.runs.claim, { runId });
assert.equal(claim.kind, "claimed");
if (claim.kind !== "claimed") throw new Error("Could not claim fixture");
let seq = claim.nextSeq;
const page = () => pageView.parse({ snapshotId: randomUUID(), origin: "https://example.test", targets: [{ ref: 1, words: "Read more", control: { kind: "submit" } }], truncated: false });
const body = (view?: ReturnType<typeof page>, name = "browser_snapshot") => ({ kind: "toolResult" as const, toolCallId: randomUUID(), name, outcome: "ok" as const, output: "bounded text", truncated: false, ...(view === undefined ? {} : { page: JSON.stringify(view) }) });
const append = async (value: ReturnType<typeof body>) => await service.mutation(api.runs.append, { runId, leaseToken: claim.leaseToken, expectedSeq: seq++, body: value });
const read = () => service.query(api.pages.ofRun, { runId });
const first = page();
const firstBody = { ...body(first), screen: { view: JSON.stringify({ width: 100, height: 100, windows: [], active: null, marks: [], unlisted: 0, silent: [] }) } };
const stored = await append(firstBody);
assert.ok(!("page" in stored));
assert.ok(!("screen" in stored));
const firstRow = await read();
assert.equal(firstRow?.view, JSON.stringify(first));
assert.equal(firstRow?.seq, seq - 1);
for (const untrusted of [owner, stranger, anonymous]) await assert.rejects(untrusted.query(api.pages.ofRun, { runId }));
await assert.rejects(owner.mutation(api.runs.append, { runId, leaseToken: claim.leaseToken, expectedSeq: seq, body: body(page()) }));
console.log("ok exact page and identity retained, append/read service isolation, history stripped");
for (const fence of [{ leaseToken: "stale", expectedSeq: seq }, { leaseToken: claim.leaseToken, expectedSeq: seq - 1 }, { leaseToken: claim.leaseToken, expectedSeq: seq + 1 }]) {
  await assert.rejects(service.mutation(api.runs.append, { runId, ...fence, body: body(page()) }));
  assert.deepEqual(await read(), firstRow);
}
const tooLarge = { ...body(), page: "😀".repeat(PAGE_LIMITS.jsonBytes) };
await assert.rejects(service.mutation(api.runs.append, { runId, leaseToken: claim.leaseToken, expectedSeq: seq, body: tooLarge }));
assert.deepEqual(await read(), firstRow);
console.log("ok stale lease/sequence and byte-limit rejection leave page and sequence unchanged");
const newest = page();
await append(body(newest));
assert.equal((await read())?.view, JSON.stringify(newest));
await append(body(undefined, "shell"));
assert.equal((await read())?.view, JSON.stringify(newest));
await append(body());
assert.equal(await read(), null);
await append(body(page()));
const inspection = internal("pageChecks:inspect", { runId });
assert.ok(inspection && typeof inspection === "object" && "pages" in inspection && Array.isArray(inspection.pages));
assert.equal(inspection.pages.length, 1);
assert.ok("run" in inspection && inspection.run && typeof inspection.run === "object" && "ownerId" in inspection.run);
assert.equal(inspection.pages[0].ownerId, inspection.run.ownerId);
const events = await service.query(api.runs.eventsPage, { runId, paginationOpts: { numItems: 100, cursor: null } });
assert.ok(events.page.every((event) => !("page" in event.body) && !("screen" in event.body)));
console.log("ok latest replacement, browser omission clears, nonbrowser omission preserves, one row");
await service.mutation(api.runs.finish, { runId, leaseToken: claim.leaseToken, state: { kind: "done" } });
assert.equal(await read(), null);
for (const state of [{ kind: "failed", reason: "fixture" }, { kind: "cancelled" }] as const) {
  const id = await owner.mutation(api.threads.send, { threadId, text: "Terminal fixture" });
  const claimed = await service.mutation(api.runs.claim, { runId: id });
  assert.equal(claimed.kind, "claimed");
  if (claimed.kind !== "claimed") throw new Error("Could not claim terminal fixture");
  await service.mutation(api.runs.append, { runId: id, leaseToken: claimed.leaseToken, expectedSeq: claimed.nextSeq, body: body(page()) });
  await service.mutation(api.runs.finish, { runId: id, leaseToken: claimed.leaseToken, state });
  assert.equal(await service.query(api.pages.ofRun, { runId: id }), null);
}
console.log("ok done, failed and cancelled terminal cleanup");
const routineId = internal("pageChecks:routine", { botId });
assert.equal(typeof routineId, "string");
const routine = (await service.query(api.runs.listQueued, {})).find((id) => id === routineId);
assert.ok(routine, "The fixture returned a queued run ID");
const routineClaim = await service.mutation(api.runs.claim, { runId: routine });
assert.equal(routineClaim.kind, "claimed");
if (routineClaim.kind !== "claimed") throw new Error("Could not claim routine fixture");
assert.equal(routineClaim.capability, "readOnly");
await service.mutation(api.runs.append, { runId: routine, leaseToken: routineClaim.leaseToken, expectedSeq: routineClaim.nextSeq, body: body(page()) });
assert.ok(await service.query(api.pages.ofRun, { runId: routine }));
internal("pageChecks:purge", { runId: routine });
const purged = internal("pageChecks:inspect", { runId: routine });
assert.ok(purged && typeof purged === "object" && "pages" in purged);
assert.deepEqual(purged.pages, []);
internal("pageChecks:purge", { runId: routine });
assert.equal(await service.query(api.pages.ofRun, { runId: routine }), null);
console.log("ok routine logged-out page retained, direct purge removes live page and run");
await owner.mutation(api.bots.remove, { botId });
console.log("verify:pages passed (local backend)");
